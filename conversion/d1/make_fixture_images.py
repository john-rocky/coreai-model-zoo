class Canvas:
    """A picture and the shapes on it (kind, color name, area in pixels)."""

    def __init__(self, w: int, h: int, bg=(255, 255, 255)):
        self.im = Image.new("RGB", (w, h), bg)
        self.d = ImageDraw.Draw(self.im)
        self.shapes: list[dict] = []

    def circle(self, cx, cy, r, color):
        self.d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=COLORS[color])
        self.shapes.append({"kind": "circle", "color": color, "area": round(math.pi * r * r)})

    def rect(self, x0, y0, x1, y1, color):
        self.d.rectangle([x0, y0, x1, y1], fill=COLORS[color])
        self.shapes.append({"kind": "square" if x1 - x0 == y1 - y0 else "rectangle", "color": color,
                            "area": (x1 - x0) * (y1 - y0)})

    def triangle(self, cx, cy, base, height, color):
        self.d.polygon([(cx - base / 2, cy + height / 2), (cx + base / 2, cy + height / 2), (cx, cy - height / 2)],
                       fill=COLORS[color])
        self.shapes.append({"kind": "triangle", "color": color, "area": round(base * height / 2)})

    def bands(self, colors, horizontal=True):
        w, h = self.im.size
        n = len(colors)
        for i, c in enumerate(colors):
            if horizontal:
                self.d.rectangle([0, i * h // n, w, (i + 1) * h // n], fill=c)
            else:
                self.d.rectangle([i * w // n, 0, (i + 1) * w // n, h], fill=c)

    def gradient(self, top, bottom):
        w, h = self.im.size
        for y in range(h):
            t = y / max(1, h - 1)
            self.d.line([(0, y), (w, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(top, bottom)))

    def lattice(self, step, color=(150, 150, 150), width=3):
        w, h = self.im.size
        for x in range(step, w, step):
            self.d.line([(x, 0), (x, h)], fill=color, width=width)
        for y in range(step, h, step):
            self.d.line([(0, y), (w, y)], fill=color, width=width)

    def scatter(self, rng: random.Random, n: int, r_min: int, r_max: int, colors, kinds, keep_out=()):
        """n small shapes at non-overlapping random spots (bounding circles 6 px apart, off `keep_out` discs)."""
        w, h = self.im.size
        placed = list(keep_out)
        for _ in range(n):
            for _try in range(2000):
                r = rng.randint(r_min, r_max)
                cx, cy = rng.randint(r + 4, w - r - 4), rng.randint(r + 4, h - r - 4)
                if all(math.hypot(cx - x, cy - y) > r + q + 6 for x, y, q in placed):
                    break
            else:
                raise RuntimeError("no room for another shape")
            placed.append((cx, cy, r))
            kind, color = rng.choice(kinds), rng.choice(colors)
            if kind == "circle":
                self.circle(cx, cy, r, color)
            elif kind == "square":
                s = round(r * 1.4)
                self.rect(cx - s // 2, cy - s // 2, cx - s // 2 + s, cy - s // 2 + s, color)
            else:
                self.triangle(cx, cy, round(r * 1.8), round(r * 1.6), color)
        return placed


