#!/usr/bin/env python3
"""Fixture pictures + image records for the d1-3B vision path, drawn from nothing.

Every picture is generated here with Pillow's drawing primitives (rectangles, ellipses, polygons, lines, flat and
graded fills) from a fixed seed; no photo, font or downloaded asset is involved, there is no text in any picture, and
nothing real is depicted, so the pictures are published under CC0-1.0. The twelve sizes cover the processor's paths
(`vision_host.py` section 2): one crop at native aspect (384x384, 384x256, 256x384, 640x480, 480x640, 300x300),
512-px tiles + thumbnail (1024x768, 768x1024, 1024x1024), a wide picture that stays one crop (1200x400) and the provider's 1-megapixel cap
before the tiles (1600x1200, 2048x1536).

Every record is `{id, source, request: {state, questions: {qid: {type, instructions, criteria}}}, images: [path],
gold: {qid: key}, note}`: `request` is the arguments of d1's `model.system_one(state, questions, images=...)`, the
gold keys follow `make_fixtures.py` (a criteria name for choice, "true" / "false" for noul, the level index as a
string for score) and come from what was drawn (`drawn` in meta.json):

    count    choice  "How many shapes are in the picture?"  one / two / three / four_or_more
    largest  choice  "What color is the largest shape?"     red / orange / yellow / green / blue / purple
    circle   noul    "Is there a circle in the picture?"
    crowded  score   "How crowded is the picture?"          0 Nearly empty (1-2 shapes) / 1 A few shapes (3-8)
                                                            / 2 Packed with shapes (9+)

A shape is a saturated circle, square / rectangle or triangle; bands, gradients and lattice lines are background. The
largest shape (by drawn area) is at least 1.4x the next one of another color.

`card_cats` is the model card's image example (README.md of LiquidAI/d1-3B @ da1fe36a): its request as printed and the
COCO URL it loads. The picture is NOT fetched or stored by this file: the record is for a measurement only and is not
part of the published fixture (a third-party photo).

    python make_fixture_images.py     # -> $ZOO_WORK_ROOT/_d1_3b/fixtures/{images/*.png, images/meta.json, image_records.json}

Two more sets for the Swift host's pixel gate (`gate_swift_pixels.py`); neither adds a record:

    --random   images_random/random_<w>x<h>.png: the six random pictures test_vision_host.py draws (NumPy
               default_rng(0), rng.integers(0, 256, (h, w, 3), uint8) in RANDOM_SIZES order), stored losslessly
    --exif     images_exif/<id>_rot90_o6.jpg: a drawn picture turned 90 degrees clockwise and saved as a JPEG (Pillow,
               quality 95) whose EXIF Orientation is 6, so a reader that applies the tag turns it another 90 degrees
               clockwise (the card's `load_image` = `ImageOps.exif_transpose` then `convert("RGB")`: img01 rotated
               180 degrees); <id>_rot90_o6.png = exactly those decoded and transposed pixels, lossless, no EXIF, to
               tell a decoder's difference from an orientation error. img01 (384x384, the pair the launch names) is
               square, so its crop plan cannot show a wrong orientation; img04 (640x480 -> stored 480x640) can.

The drawing is deterministic: a re-run reproduces each picture's raw-RGB sha256 (the PNG bytes depend on zlib, the
JPEG bytes on Pillow's libjpeg).
"""
