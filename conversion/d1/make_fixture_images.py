def facts(c: Canvas) -> dict:
    shapes = c.shapes
    n = len(shapes)
    by_area = sorted(shapes, key=lambda s: -s["area"])
    other = next((s for s in by_area[1:] if s["color"] != by_area[0]["color"]), None)
    return {"n_shapes": n, "has_circle": any(s["kind"] == "circle" for s in shapes),
            "largest_color": by_area[0]["color"], "largest_area": by_area[0]["area"],
            "next_other_color_area": other["area"] if other else None,
            "crowded_level": 0 if n <= 2 else 1 if n <= 8 else 2,
            "kinds": sorted({s["kind"] for s in shapes}), "colors": sorted({s["color"] for s in shapes})}


def gold_for(qid: str, f: dict) -> str:
    if qid == "count":
        return {1: "one", 2: "two", 3: "three"}.get(f["n_shapes"], "four_or_more")
    if qid == "largest":
        return f["largest_color"]
    if qid == "circle":
        return "true" if f["has_circle"] else "false"
    return str(f["crowded_level"])


