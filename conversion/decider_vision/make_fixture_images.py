"""Fixture images + row definitions for the decider-2b-vision oracle, drawn from nothing.

Every image is generated here with Pillow's drawing primitives (rectangles, ellipses, polygons);
no photo, font file or downloaded asset is involved, so the fixture can be published under
CC0-1.0. Digits are seven-segment polygons, not glyphs. No real people, companies or products
appear in the pictures or in the text this file defines. The game-frame contexts are the
author's training prompts (`decider/games/envs.py` `intro` + `decider/games/frames_data.py`
VIS_INTRO), kept word for word except that the two game titles and their maker's name are
replaced by a plain description ("a two-paddle ball game", "a brick-breaking game").

The rows follow three input shapes the checkpoint was trained or benchmarked on:

* the author's MPS bench case (`decider/bench/mps.py`): a solid 224x224 `Image.new("RGB",
  (224, 224), color)` with "Identify the dominant color in the image." and
  `Q("What color is shown?", ["red", "green", "blue"])`;
* The Cauldron form (`decider/vision/data.py`): context "This is a visual question about the
  image.", one or more lettered questions;
* the game-frame form (`decider/games/frames_data.py`): `f"{intro} The image shows the current
  game screen."` + "What should you do right now?" with the game's own option list;

plus text-only rows (no image), the decider's text readout through the same model.

    python3 conversion/decider_vision/make_fixture_images.py            # -> $ZOO_WORK_ROOT/_decider2bv/fixtures
    python3 conversion/decider_vision/make_fixture_images.py --out-dir /tmp/fx

Writes `images/<name>.png`, `meta.json` (size, PNG and raw-RGB sha256, the generator and its
arguments, licence) and `rows.json` (context, questions, options, the intended answer). The
drawing is deterministic: re-running reproduces the raw-RGB sha256 exactly (the PNG bytes
depend on the zlib build, the pixels do not).
"""
