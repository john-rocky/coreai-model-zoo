def minigrid_forward_256x240():
    # An 8x8 MiniGrid-Empty-style room, 30 px tiles: grey walls, black floor, green goal at (6,6),
    # red agent at (3,6) facing east with the goal straight ahead -> "move forward". Cells in the
    # agent's view are lightened as the environment's renderer highlights them.
    im, d = canvas(256, 240, (0, 0, 0))
    t, ox = 30, 8
    agent, goal = (3, 6), (6, 6)

    def lit(col):
        return tuple(int(v + (255 - v) * 0.3) for v in col)

    for y in range(8):
        for x in range(8):
            wall = x in (0, 7) or y in (0, 7)
            col = (100, 100, 100) if wall else (0, 0, 0)
            if (x, y) == goal:
                col = (0, 255, 0)
            if 3 <= x <= 7 and 3 <= y <= 7:           # the 7x7 egocentric view, clipped to the room
                col = lit(col)
            x0, y0 = ox + x * t, y * t
            d.rectangle([x0, y0, x0 + t - 1, y0 + t - 1], fill=col)
            d.line([(x0, y0), (x0 + t - 1, y0)], fill=(100, 100, 100))
            d.line([(x0, y0), (x0, y0 + t - 1)], fill=(100, 100, 100))
    ax, ay = ox + agent[0] * t, agent[1] * t
    d.polygon([(ax + 0.12 * t, ay + 0.19 * t), (ax + 0.87 * t, ay + 0.50 * t), (ax + 0.12 * t, ay + 0.81 * t)],
              fill=(255, 0, 0))
    return im


