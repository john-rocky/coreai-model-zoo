def check_rows(rows):
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids)), "duplicate row id"
    for r in rows:
        assert r["image"] is None or r["image"] in IMAGES, r
        text = r["context"] + " ".join(qq["text"] + " " + " ".join(qq["options"]) for qq in r["questions"])
        # A state quoting "Answer" would let the checkpoint's slot finder and GitHub main's disagree.
        assert "Answer" not in text, r["id"]
    counts = sorted({len(qq["options"]) for r in rows for qq in r["questions"]})
    assert counts == list(range(2, 11)), counts


def write_if_changed(path: Path, data: bytes) -> bool:
    """Replace `path` atomically and only when its bytes change, so a reader never sees a partial file."""
    if path.exists() and path.read_bytes() == data:
        return False
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out-dir", default=str(work_path("_decider2bv", "fixtures")))
    args = ap.parse_args()
    out = Path(args.out_dir).expanduser()
    (out / "images").mkdir(parents=True, exist_ok=True)
    check_rows(ROWS)

    meta, changed = [], []
    for name, (fn, kw) in IMAGES.items():
        im = fn(**kw)
        assert im.mode == "RGB"
        path = out / "images" / f"{name}.png"
        buf = io.BytesIO()
        im.save(buf, format="PNG")
        png = buf.getvalue()
        assert Image.open(io.BytesIO(png)).convert("RGB").tobytes() == im.tobytes(), name  # lossless round trip
        if write_if_changed(path, png):
            changed.append(path.name)
        meta.append({
            "name": name, "path": f"images/{name}.png", "size": list(im.size),
            "sha256": hashlib.sha256(png).hexdigest(),
            "rgb_sha256": hashlib.sha256(im.tobytes()).hexdigest(),
            "generator": {"script": "conversion/decider_vision/make_fixture_images.py", "function": fn.__name__, "args": kw},
            "license": LICENSE,
        })
    for name, obj in (("meta.json", {"license": LICENSE, "images": meta}), ("rows.json", {"rows": ROWS})):
        if write_if_changed(out / name, (json.dumps(obj, indent=1, ensure_ascii=False) + "\n").encode()):
            changed.append(name)
    n_slots = sum(len(r["questions"]) for r in ROWS)
    n_multi = sum(len(r["questions"]) > 1 for r in ROWS)
    n_text = sum(r["image"] is None for r in ROWS)
    print(f"{len(meta)} images, {len(ROWS)} rows ({n_text} text-only, {n_multi} multi-question), {n_slots} slots -> {out}")
    print(f"files rewritten: {changed if changed else 'none (all byte-identical)'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
